app.get("/", (req, res) => {
    const baseUrl = `${req.protocol}://${req.get("host")}`;
    res.status(200).type("html").send(guidePage(baseUrl));
});

/* ---------- GET /health ---------- */
app.get("/health", async (req, res) => {
    try {
        await pool.query("SELECT 1");
        res.status(200).json({ status: "ok", database: "connected" });
    } catch (error) {
        console.error("Health check failed:", error.message);
        res.status(503).json({
            status: "error",
            database: "unavailable",
            message: "The database is not responding."
        });
    }
});

/* ---------- Record routes ---------- */
app.use("/api/records", require("./routes/records"));

/* ---------- Unknown routes -> JSON 404 ---------- */
app.use((req, res) => {
    res.status(404).json({ message: "Route not found." });
});

/* ---------- Error handler (four parameters) ---------- */
app.use((error, req, res, next) => {
    // Malformed JSON body
    if (error.type === "entity.parse.failed") {
        return res.status(400).json({ message: "Malformed JSON in the request body." });
    }

    // Body too large
    if (error.type === "entity.too.large") {
        return res.status(400).json({ message: "Request body is too large." });
    }

    // Log the details on the server, send a clear message to the client
    console.error(error);
    res.status(500).json({ message: "Unexpected server error. Please try again." });
});

/* ---------- Start ---------- */
const port = process.env.PORT || 3000;

app.listen(port, "0.0.0.0", () => {
    console.log(`Server listening on port ${port}`);
});
