require("dotenv").config();
const express = require("express");
const cors = require("cors");
const pool = require("./db");

const app = express();

/* ---------- Details shown on the API guide page ---------- */
const PROJECT_NAME = "Campus Maintenance Requests API";
const STUDENT_NAME = "Mwamba Sampa";
const STUDENT_NUMBER = "202506234";

/* ---------- Middleware ---------- */
// Render sits behind a proxy, so this makes req.protocol report https correctly
app.set("trust proxy", 1);

const origins = (process.env.CLIENT_ORIGINS || "")
    .split(",")
    .map((value) => value.trim())
    .filter(Boolean);

app.use(cors({ origin: origins }));
app.use(express.json());

/* ---------- GET / : API guide for the marker ---------- */
